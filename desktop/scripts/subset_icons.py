"""Subset Material Symbols Rounded to the icons listed in src/theme/icons.json (spec D11.g).

The full font is 5.4 MB. Icons are drawn by their private-use codepoints, so the subset keeps
only those codepoints (no ligature table) and every variable axis. Writes:

- src/assets/fonts/material-symbols-rounded-subset.woff2
- src/theme/icons.generated.ts, mapping each icon name to its codepoint

Run from desktop/: uv run --with fonttools --with brotli python scripts/subset_icons.py
"""

from __future__ import annotations

import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

HERE = Path(__file__).resolve().parent.parent
SOURCE = HERE / "node_modules/material-symbols/material-symbols-rounded.woff2"
NAMES = HERE / "src/theme/icons.json"
FONT_OUT = HERE / "src/assets/fonts/material-symbols-rounded-subset.woff2"
MAP_OUT = HERE / "src/theme/icons.generated.ts"


def ligature_glyphs(font: TTFont) -> dict[str, str]:
    """Icon name -> glyph name, read from the font's ligature substitutions."""
    letters = {glyph: chr(code) for code, glyph in font.getBestCmap().items() if code < 128}
    found: dict[str, str] = {}
    for lookup in font["GSUB"].table.LookupList.Lookup:
        for table in lookup.SubTable:
            if table.LookupType == 7:
                table = table.ExtSubTable
            if table.LookupType != 4:
                continue
            for first, ligatures in table.ligatures.items():
                for ligature in ligatures:
                    parts = [first, *ligature.Component]
                    if all(part in letters for part in parts):
                        found.setdefault("".join(letters[p] for p in parts), ligature.LigGlyph)
    return found


def main() -> None:
    names = json.loads(NAMES.read_text())
    assert names == sorted(set(names)), "icons.json must be sorted and unique"
    font = TTFont(SOURCE)
    glyphs = ligature_glyphs(font)
    private = {
        glyph: code
        for code, glyph in sorted(font.getBestCmap().items())
        if 0xE000 <= code <= 0xF8FF or code >= 0xF0000
    }
    codes = {}
    for name in names:
        glyph = glyphs.get(name)
        if glyph is None or glyph not in private:
            raise SystemExit(f"Material Symbols has no icon named {name!r}")
        codes[name] = private[glyph]
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = []
    options.name_IDs = ["*"]
    options.notdef_outline = True
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codes.values())
    subsetter.subset(font)
    FONT_OUT.parent.mkdir(parents=True, exist_ok=True)
    font.flavor = "woff2"
    font.save(FONT_OUT)
    lines = [
        "// Generated by scripts/subset_icons.py from src/theme/icons.json; do not edit.",
        "export const ICONS = {",
        *(f'  {name}: 0x{code:x},' for name, code in codes.items()),
        "} as const;",
        "",
        "export type IconName = keyof typeof ICONS;",
        "",
    ]
    MAP_OUT.write_text("\n".join(lines))
    print(f"{len(codes)} icons, {FONT_OUT.stat().st_size:,} bytes")


if __name__ == "__main__":
    main()
