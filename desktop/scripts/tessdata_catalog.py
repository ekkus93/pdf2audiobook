"""Write the catalog of OCR language files the desktop app can add (self-contained app SC4).

    python3 desktop/scripts/tessdata_catalog.py    # needs the GitHub CLI (`gh`) and network

Lists every `.traineddata` file in tesseract-ocr/tessdata_fast at the pinned tag, with its size
and git blob hash (SHA-1 of "blob <size>\\0" + content), which GitHub's tree API reports. The
engine checks each download against both. Output: desktop/engine/tessdata.json.
"""

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REPO = "tesseract-ocr/tessdata_fast"
TAG = "4.1.0"


def main() -> None:
    def api(path: str) -> dict:
        done = subprocess.run(["gh", "api", path], check=True, capture_output=True, text=True)
        return json.loads(done.stdout)

    target = api(f"repos/{REPO}/git/ref/tags/{TAG}")["object"]
    if target["type"] == "tag":  # An annotated tag: follow it to the commit.
        target = api(f"repos/{REPO}/git/tags/{target['sha']}")["object"]
    commit = target["sha"]
    tree = api(f"repos/{REPO}/git/trees/{commit}")["tree"]
    languages = {
        item["path"].removesuffix(".traineddata"): {"size": item["size"], "git_blob": item["sha"]}
        for item in sorted(tree, key=lambda item: item["path"])
        if item["path"].endswith(".traineddata")
    }
    catalog = {
        "comment": "Generated by desktop/scripts/tessdata_catalog.py; do not edit.",
        "repo": REPO,
        "tag": TAG,
        "commit": commit,
        "license": "Apache-2.0",
        "url": f"https://raw.githubusercontent.com/{REPO}/{commit}/{{language}}.traineddata",
        "languages": languages,
    }
    out = ROOT / "desktop" / "engine" / "tessdata.json"
    out.write_text(json.dumps(catalog, indent=2) + "\n", encoding="utf-8")
    print(out.relative_to(ROOT), len(languages), "languages")


if __name__ == "__main__":
    main()
